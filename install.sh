# install.sh — install, update or remove vdl2-observatory on this machine:
# the vdl2-sniffer receiver on an RTL-SDR (live page on :8889) and the VDL2
# Observatory dashboard (:8891), as systemd services that start at boot.
#
# Usage (from the repo checkout, as your normal user — it sudo's as needed):
#     ./install.sh                 first install (asks a few questions)
#     ./install.sh --update        git pull, rebuild, test, reinstall, restart
#     ./install.sh --reconfigure   ask the questions again, then reinstall
#     ./install.sh --uninstall     remove services and program files
#
# Options:
#     --yes          don't ask; take the defaults (or the existing config)
#     --no-deps      skip installing packages (you've done it yourself)
#     --dry-run      print what would be done as root, change nothing
#     -h, --help     show this help
#
# Where things go:
#     /opt/vdl2-observatory/        program files (binary, data, observatory)
#     /etc/vdl2-observatory.conf    your settings — edit this, not the units
#     /var/lib/vdl2-observatory/    archive/ (JSONL) and observatory.db
#
# Re-running is safe. Settings, archive and database survive updates and
# uninstall. A receiver set up by hand from systemd/ (user units) is taken
# over: its settings are offered, its archive copied, its units disabled.
#
set -euo pipefail

# ---- pretty output ----------------------------------------------------------
if [ -t 1 ]; then B=$'\033[1m'; G=$'\033[32m'; Y=$'\033[33m'; R=$'\033[31m'; Z=$'\033[0m'
else B=""; G=""; Y=""; R=""; Z=""; fi
say()  { printf '%s\n' "$*"; }
info() { printf '\n%s==>%s %s\n' "$B" "$Z" "$*"; }
ok()   { printf '  %sok%s   %s\n' "$G" "$Z" "$*"; }
warn() { printf '  %swarn%s %s\n' "$Y" "$Z" "$*"; }
die()  { printf '  %serror%s %s\n' "$R" "$Z" "$*" >&2; exit 1; }

# ---- fixed locations --------------------------------------------------------
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BUILD_DIR="$REPO_ROOT/build-install"
PREFIX=/opt/vdl2-observatory
CONF=/etc/vdl2-observatory.conf
DATA_DIR=/var/lib/vdl2-observatory
ARCHIVE_DIR="$DATA_DIR/archive"
DB_PATH="$DATA_DIR/observatory.db"
UNIT_DIR=/etc/systemd/system
SNIFFER_UNIT="$UNIT_DIR/vdl2-sniffer.service"
OBS_UNIT="$UNIT_DIR/vdl2-observatory.service"
ROLLUP_UNIT="$UNIT_DIR/vdl2-rollup.service"
ROLLUP_TIMER="$UNIT_DIR/vdl2-rollup.timer"
MARKER="# Generated by vdl2-observatory install.sh"
LIBACARS_TAG=v2.2.1
# A receiver set up by hand from systemd/: user units and their settings.
USER_UNIT_DIR="$HOME/.config/systemd/user"
USER_ENV="$HOME/.config/vdl2-sniffer.env"

# ---- args -------------------------------------------------------------------
MODE=install; ASSUME_YES=0; DEPS=1; DRY_RUN=0; PULLED=0
ORIG_ARGS=("$@")
while [ $# -gt 0 ]; do
  case "$1" in
    --update)      MODE=update;;
    --reconfigure) MODE=reconfigure;;
    --uninstall)   MODE=uninstall;;
    --yes|-y)      ASSUME_YES=1;;
    --no-deps)     DEPS=0;;
    --dry-run)     DRY_RUN=1;;
    --pulled)      PULLED=1;;   # internal: --update re-running the new script
    -h|--help)     sed -n '2,29p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0;;
    *) die "unknown option: $1 (try --help)";;
  esac
  shift
done

# ---- helpers ----------------------------------------------------------------
# Everything that changes the system outside the checkout goes through as_root
# (or as_user for the user's own services), so --dry-run can show it without
# doing it.
as_root() {
  if [ "$DRY_RUN" -eq 1 ]; then printf '  %s[dry-run]%s %s\n' "$Y" "$Z" "$*"; return 0; fi
  sudo "$@"
}
as_user() {
  if [ "$DRY_RUN" -eq 1 ]; then printf '  %s[dry-run]%s %s\n' "$Y" "$Z" "$*"; return 0; fi
  "$@"
}
# Write stdin to a root-owned file (mode $2).
root_write() {
  local dst="$1" mode="$2" tmp
  tmp="$(mktemp)"; cat > "$tmp"
  if [ "$DRY_RUN" -eq 1 ]; then
    printf '  %s[dry-run]%s write %s:\n' "$Y" "$Z" "$dst"; sed 's/^/      | /' "$tmp"
  else
    sudo install -m "$mode" "$tmp" "$dst"
  fi
  rm -f "$tmp"
}
# Ask a question on the terminal; $2 is the default. --yes takes the default.
ask() {
  local q="$1" def="$2" ans
  if [ "$ASSUME_YES" -eq 1 ] || [ ! -r /dev/tty ]; then printf '%s' "$def"; return; fi
  printf '  %s [%s]: ' "$q" "$def" > /dev/tty
  read -r ans < /dev/tty || ans=""
  printf '%s' "${ans:-$def}"
}
yes_no() { case "$(ask "$1 (y/n)" "$2")" in [Yy]*) return 0;; *) return 1;; esac; }
have() { command -v "$1" >/dev/null 2>&1; }
user_systemctl() { systemctl --user "$@" 2>/dev/null; }

# ---- preflight --------------------------------------------------------------
info "Preflight"
[ "$(uname -s)" = Linux ] || die "Linux only"
[ "$(id -u)" -ne 0 ] || die "run as your normal user, not root — it uses sudo when it needs to"
have systemctl || die "systemd is required"
have sudo || die "sudo is required"
if [ "$DRY_RUN" -eq 0 ]; then
  sudo -v || die "sudo failed"
fi
RUN_USER="$(id -un)"
ok "user: $RUN_USER   arch: $(uname -m)   $(. /etc/os-release 2>/dev/null; echo "${PRETTY_NAME:-unknown OS}")"

# ---- uninstall --------------------------------------------------------------
if [ "$MODE" = uninstall ]; then
  info "Removing services and program files"
  as_root systemctl disable --now vdl2-sniffer.service vdl2-observatory.service vdl2-rollup.timer 2>/dev/null || true
  as_root rm -f "$SNIFFER_UNIT" "$OBS_UNIT" "$ROLLUP_UNIT" "$ROLLUP_TIMER" /usr/local/bin/vdl2-sniffer
  as_root rm -rf "$PREFIX"
  as_root systemctl daemon-reload
  ok "removed. Kept: $CONF and $DATA_DIR (delete by hand for a clean slate)"
  exit 0
fi

# ---- update: pull first, so everything below builds the new source ----------
if [ "$MODE" = update ] && [ "$PULLED" -eq 0 ]; then
  [ -f "$CONF" ] || die "no $CONF — run ./install.sh first"
  info "Updating the checkout"
  have git || die "git not found"
  git -C "$REPO_ROOT" pull --ff-only \
    || die "git pull failed (local changes or a diverged branch?) — fix the checkout and re-run"
  ok "now at $(git -C "$REPO_ROOT" describe --always --dirty --tags)"
  # The pull may have changed this script; carry on with the new one.
  exec "$REPO_ROOT/install.sh" "${ORIG_ARGS[@]}" --pulled
fi

# ---- packages ---------------------------------------------------------------
install_libacars_from_source() {
  info "Building libacars $LIBACARS_TAG from source (no distro package)"
  local src; src="$(mktemp -d)"
  git clone -q --depth 1 --branch "$LIBACARS_TAG" https://github.com/szpajder/libacars "$src/libacars" \
    || die "could not clone libacars"
  cmake -S "$src/libacars" -B "$src/libacars/build" -DCMAKE_BUILD_TYPE=Release >/dev/null \
    && cmake --build "$src/libacars/build" -j"$(nproc)" >/dev/null \
    || die "libacars build failed"
  as_root cmake --install "$src/libacars/build" >/dev/null
  as_root ldconfig
  rm -rf "$src"
  ok "libacars $LIBACARS_TAG installed to /usr/local"
}

if [ "$DEPS" -eq 1 ]; then
  info "Packages"
  if have apt-get; then
    # Needed to build and run at all: one apt call, and a failure stops the
    # install. rtl-sdr brings the udev rules that let plugdev open the dongle.
    CORE=(build-essential cmake pkg-config git python3 curl usbutils librtlsdr-dev rtl-sdr
          zlib1g-dev libxml2-dev)
    as_root apt-get install -y -q --no-install-recommends "${CORE[@]}" \
      || die "could not install the build tools — see apt's message above"
    ok "build tools and RTL-SDR support installed"
    if pkg-config --exists libacars-2 2>/dev/null; then
      ok "libacars $(pkg-config --modversion libacars-2) already present"
    elif apt-cache show libacars-dev >/dev/null 2>&1; then
      as_root apt-get install -y -q libacars-dev
    else
      install_libacars_from_source
    fi
  else
    warn "not a Debian/Ubuntu system — install by hand: cmake, a C/C++ compiler, librtlsdr,"
    warn "libacars-2, python3 (see README), then re-run with --no-deps"
  fi
fi

# ---- build + test -----------------------------------------------------------
info "Building"
cmake -S "$REPO_ROOT" -B "$BUILD_DIR" -DCMAKE_BUILD_TYPE=Release > "$BUILD_DIR.log" 2>&1 \
  && cmake --build "$BUILD_DIR" -j"$(nproc)" >> "$BUILD_DIR.log" 2>&1 \
  || { tail -20 "$BUILD_DIR.log"; die "build failed — full log: $BUILD_DIR.log"; }
BIN="$BUILD_DIR/vdl2-sniffer"
ok "built $BIN"
grep -q 'librtlsdr .*: --rtlsdr on' "$BUILD_DIR.log" \
  || die "built without librtlsdr, so it can't read the RTL-SDR — install librtlsdr-dev and re-run"
if grep -q 'libacars-2 .*: ACARS reassembly and decoding on' "$BUILD_DIR.log"; then
  ok "libacars enabled (multi-block ACARS, CPDLC, ADS-C)"
else
  warn "built WITHOUT libacars — ACARS blocks only, no reassembly or CPDLC/ADS-C decoding"
fi

info "Testing"
"$REPO_ROOT/tests/run_tests.sh" "$BUILD_DIR" > "$BUILD_DIR/tests.log" 2>&1 \
  || { tail -20 "$BUILD_DIR/tests.log"; die "tests failed — not installing. Log: $BUILD_DIR/tests.log"; }
ok "$(grep '^RESULT' "$BUILD_DIR/tests.log")"

# ---- device access ----------------------------------------------------------
# The service runs headless as $RUN_USER with SupplementaryGroups=plugdev, so
# the dongle's USB node must be group-writable by plugdev. The rtl-sdr
# package's rules do that on Debian and Ubuntu; this rule covers distros
# whose rules only grant the user logged in at the screen.
info "Device access"
SDR_RULE=/etc/udev/rules.d/52-vdl2-observatory-rtlsdr.rules
if getent group plugdev >/dev/null 2>&1; then
  root_write "$SDR_RULE" 0644 <<'RULE'
# Written by vdl2-observatory install.sh: let the plugdev group (the
# vdl2-sniffer service's) open an RTL-SDR, logged in at the screen or not.
SUBSYSTEM=="usb", ATTR{idVendor}=="0bda", ATTR{idProduct}=="2832", MODE="0660", GROUP="plugdev"
SUBSYSTEM=="usb", ATTR{idVendor}=="0bda", ATTR{idProduct}=="2838", MODE="0660", GROUP="plugdev"
RULE
  as_root udevadm control --reload-rules
  as_root udevadm trigger --subsystem-match=usb --attr-match=idVendor=0bda
  as_root udevadm settle --timeout=10 || true
  ok "udev rule: plugdev can open an RTL-SDR ($SDR_RULE)"
  if [[ " $(id -nG "$RUN_USER") " != *" plugdev "* ]]; then
    as_root usermod -aG plugdev "$RUN_USER"
    warn "added $RUN_USER to plugdev: log out and back in to use the dongle from your own shell"
  fi
else
  warn "no plugdev group on this system: the service may not be able to open the RTL-SDR"
fi
# RTL-SDRs on USB now, one "serial node group mode" line each.
rtl_devices() {
  local d v p
  for d in /sys/bus/usb/devices/*; do
    [ -r "$d/idVendor" ] || continue
    v="$(<"$d/idVendor")"; p="$(<"$d/idProduct")"
    case "$v:$p" in 0bda:2832|0bda:2838) ;; *) continue;; esac
    node="$(printf '/dev/bus/usb/%03d/%03d' "$(<"$d/busnum")" "$(<"$d/devnum")")"
    printf '%s %s %s %s\n' "$(cat "$d/serial" 2>/dev/null || echo -)" "$node" \
      "$(stat -c %G "$node" 2>/dev/null)" "$(stat -c %a "$node" 2>/dev/null)"
  done
}
mapfile -t RTLS < <(rtl_devices)
for r in "${RTLS[@]}"; do
  read -r serial node g m <<<"$r"
  if { [ "$g" = plugdev ] && (( 8#${m:-0} & 8#020 )); } || (( 8#${m:-0} & 8#002 )); then
    ok "RTL-SDR serial $serial ($node): group $g, mode $m"
  else
    warn "RTL-SDR serial $serial ($node) is group $g, mode $m: the service can't open it. Unplug it and plug it back in; if the warning stays, the distro's udev rules override ours"
  fi
done
[ "${#RTLS[@]}" -gt 0 ] || warn "no RTL-SDR on USB right now"

# ---- a receiver set up by hand (systemd/ user units) ------------------------
HAND_UNIT="$USER_UNIT_DIR/vdl2-sniffer.service"
HAND=0; HAND_ARGS=""; HAND_ARCHIVE=""
if [ -f "$HAND_UNIT" ]; then
  HAND=1
  # Its flags: the unit's own (minus --web and --archive, which the new unit
  # adds) and the VDL2_ARGS in its settings file.
  exec_line="$(sed -n 's/^ExecStart=//p' "$HAND_UNIT" | head -1)"
  unit_args="$(sed 's/\$VDL2_ARGS//; s/^[^ ]* *//' <<<"$exec_line" \
    | sed -E 's/(^| )--web(=[^ ]*)?//g; s/(^| )--archive( [^-][^ ]*|=[^ ]*)?//g; s/  */ /g; s/^ //; s/ $//')"
  # systemd's EnvironmentFile takes VDL2_ARGS=a b c unquoted, which bash
  # can't source: read the value, minus any quotes around it.
  env_args="$(sed -n 's/^[[:space:]]*VDL2_ARGS=//p' "$USER_ENV" 2>/dev/null | tail -1 \
    | sed -E 's/^"(.*)"$/\1/; s/^'"'"'(.*)'"'"'$/\1/')"
  HAND_ARGS="$(echo "$unit_args $env_args" | sed 's/^ *//; s/  */ /g; s/ *$//')"
  HAND_ARCHIVE="$(sed -nE 's/.*--archive[ =]([^ ]+).*/\1/p' <<<"$exec_line" | sed "s|%h|$HOME|g")"
fi

# ---- config -----------------------------------------------------------------
if [ -f "$CONF" ] && [ "$MODE" != reconfigure ]; then
  info "Config"
  ok "keeping $CONF (./install.sh --reconfigure to redo it)"
  # shellcheck disable=SC1090
  . "$CONF"
else
  info "Config"
  WEB_PORT=8889; OBS_PORT=8891; VDL2_ARGS=""
  # shellcheck disable=SC1090
  [ -f "$CONF" ] && . "$CONF"
  if [ "$HAND" -eq 1 ] && [ -n "$HAND_ARGS" ]; then
    say "  Found a receiver set up by hand ($HAND_UNIT):  $HAND_ARGS"
  fi
  if [ "$HAND" -eq 1 ] && [ -n "$HAND_ARGS" ] && yes_no "Keep those settings" y; then
    VDL2_ARGS="$HAND_ARGS"
  else
    if [ "${#RTLS[@]}" -gt 1 ]; then
      say "  RTL-SDRs found:"
      for i in "${!RTLS[@]}"; do say "    $((i+1))) serial ${RTLS[$i]%% *}"; done
      n="$(ask "Which one" 1)"
      [[ "$n" =~ ^[0-9]+$ ]] && [ "$n" -ge 1 ] && [ "$n" -le "${#RTLS[@]}" ] || n=1
      serial="${RTLS[$((n-1))]%% *}"
      # A serial picks the same dongle after a reboot; an index may not.
      if [ "$serial" != - ]; then DEV="$serial"; else DEV=$((n-1)); fi
    else
      DEV=0
    fi
    VDL2_ARGS="--rtlsdr $DEV"
    plan="$(ask "Channel plan, us or eu" us)"
    case "$plan" in us|eu) ;; *) warn "'$plan' is not us or eu — using us"; plan=us;; esac
    [ "$plan" = us ] || VDL2_ARGS+=" --plan $plan"
    gain="$(ask "Tuner gain in dB, or auto" auto)"
    if [ "$gain" != auto ]; then
      if [[ "$gain" =~ ^[0-9]+(\.[0-9]+)?$ ]]; then VDL2_ARGS+=" --gain $gain"
      else warn "'$gain' is not a number — using auto"; fi
    fi
    ppm="$(ask "Frequency correction in ppm" 0)"
    if [ "$ppm" != 0 ]; then
      if [[ "$ppm" =~ ^-?[0-9]+$ ]]; then VDL2_ARGS+=" --ppm $ppm"
      else warn "'$ppm' is not a whole number — using 0"; fi
    fi
    yes_no "Power an LNA through the dongle's bias tee" n && VDL2_ARGS+=" --bias-tee"
    # One UDP feed: an aggregator, or a local acarshub, in dumpvdl2's JSON.
    feed="$(ask "Feed frames over UDP to an aggregator or acarshub, HOST:PORT (blank for none)" "")"
    if [ -n "$feed" ]; then
      if [[ "$feed" =~ ^[^:/[:space:]]+:[0-9]+$ ]]; then
        VDL2_ARGS+=" --udp $feed"
        st="$(ask "Station ID for that feed (blank for none)" "")"
        [ -n "$st" ] && VDL2_ARGS+=" --station-id $st"
      else
        warn "skipping '$feed' — expected HOST:PORT"
      fi
    fi
    # SBS: a port to serve on, or HOST:PORT to push to.
    sbs="$(ask "Aircraft positions as SBS/BaseStation: a port to serve, HOST:PORT to push (blank for none)" "")"
    if [ -n "$sbs" ]; then
      if [[ "$sbs" =~ ^([^:/[:space:]]+:)?[0-9]+$ ]]; then VDL2_ARGS+=" --basestation=$sbs"
      else warn "skipping '$sbs' — expected PORT or HOST:PORT"; fi
    fi
  fi
  VDL2_ARGS="$(echo "$VDL2_ARGS" | sed 's/^ *//; s/  */ /g; s/ *$//')"
  root_write "$CONF" 0644 <<EOF
# vdl2-observatory settings — written by install.sh, yours to edit.
# After changing anything:   sudo systemctl restart vdl2-sniffer
# Ports or user changed?     re-run ./install.sh so the services follow.
# All options:               vdl2-sniffer --help
#
# Archive and database always live in $DATA_DIR

# Who the services run as.
RUN_USER="$RUN_USER"

# Receiver flags (dongle, gain, feeds). --web and --archive are added for you.
VDL2_ARGS="$VDL2_ARGS"

# Live page port, and Observatory dashboard port.
WEB_PORT="$WEB_PORT"
OBS_PORT="$OBS_PORT"
EOF
  ok "wrote $CONF"
fi
: "${WEB_PORT:=8889}" "${OBS_PORT:=8891}" "${RUN_USER:=$(id -un)}"

# ---- install files ----------------------------------------------------------
# The binary finds its fix list in ../share/vdl2-sniffer; server.py finds the
# map outlines in ../data.
info "Installing program files to $PREFIX"
STAGE="$(mktemp -d)"; trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/bin" "$STAGE/share/vdl2-sniffer" "$STAGE/data" "$STAGE/observatory"
cp "$BIN" "$STAGE/bin/"
cp "$REPO_ROOT/data/waypoints.csv" "$STAGE/share/vdl2-sniffer/"
cp "$REPO_ROOT/data/outlines.json" "$STAGE/data/"
cp "$REPO_ROOT"/observatory/*.py "$STAGE/observatory/"
git -C "$REPO_ROOT" describe --always --dirty --tags > "$STAGE/VERSION" 2>/dev/null || echo unknown > "$STAGE/VERSION"
# Swap the whole tree in by rename, so the services never see half a copy.
as_root rm -rf "$PREFIX.new" "$PREFIX.old"
as_root cp -r "$STAGE" "$PREFIX.new"
as_root chmod -R a+rX "$PREFIX.new"
if [ "$DRY_RUN" -eq 1 ] || [ -d "$PREFIX" ]; then as_root mv "$PREFIX" "$PREFIX.old"; fi
as_root mv "$PREFIX.new" "$PREFIX"
as_root rm -rf "$PREFIX.old"
as_root ln -sf "$PREFIX/bin/vdl2-sniffer" /usr/local/bin/vdl2-sniffer
ok "version $(cat "$STAGE/VERSION")"

as_root mkdir -p "$ARCHIVE_DIR"
as_root chown -R "$RUN_USER:" "$DATA_DIR"
ok "data in $DATA_DIR"

# ---- take over a receiver set up by hand ------------------------------------
# Its user units hold the dongle and the ports: stop them before the system
# units start, and bring its archive along (the database is rebuilt from it).
if [ "$HAND" -eq 1 ]; then
  info "Taking over the receiver set up by hand"
  as_user systemctl --user disable --now vdl2-sniffer.service vdl2-observatory.service vdl2-rollup.timer \
    2>/dev/null || true
  BAK="$DATA_DIR/user-units.$(date +%Y%m%d-%H%M%S)"
  as_root mkdir -p "$BAK"
  for f in vdl2-sniffer.service vdl2-observatory.service vdl2-rollup.service vdl2-rollup.timer; do
    [ -f "$USER_UNIT_DIR/$f" ] || continue
    as_root cp "$USER_UNIT_DIR/$f" "$BAK/"
    as_user rm -f "$USER_UNIT_DIR/$f"
  done
  [ -f "$USER_ENV" ] && as_root cp "$USER_ENV" "$BAK/"
  as_user systemctl --user daemon-reload 2>/dev/null || true
  ok "user units stopped, disabled and removed (copies in $BAK)"
  if [ -n "$HAND_ARCHIVE" ] && [ "$HAND_ARCHIVE" != "$ARCHIVE_DIR" ] \
     && ls "$HAND_ARCHIVE"/vdl2-*.jsonl >/dev/null 2>&1; then
    n="$(ls "$HAND_ARCHIVE"/vdl2-*.jsonl | wc -l)"
    if yes_no "Copy its archive ($n days in $HAND_ARCHIVE) into $ARCHIVE_DIR" y; then
      as_root cp -n -p "$HAND_ARCHIVE"/vdl2-*.jsonl "$ARCHIVE_DIR/"
      as_root chown -R "$RUN_USER:" "$ARCHIVE_DIR"
      ok "archive copied (the originals are left where they were)"
    fi
  fi
fi

# ---- services ---------------------------------------------------------------
info "Services"
for u in "$SNIFFER_UNIT" "$OBS_UNIT" "$ROLLUP_UNIT" "$ROLLUP_TIMER"; do
  if [ -f "$u" ] && ! head -1 "$u" | grep -qF "$MARKER"; then
    BAKU="$DATA_DIR/$(basename "$u").$(date +%Y%m%d-%H%M%S)"
    as_root cp "$u" "$BAKU"
    warn "replacing a hand-written $u (saved a copy as $BAKU)"
  fi
done
GROUPS_LINE=""
getent group plugdev >/dev/null 2>&1 && GROUPS_LINE="SupplementaryGroups=plugdev"
PY="$(command -v python3)"
root_write "$SNIFFER_UNIT" 0644 <<EOF
$MARKER — don't edit; change $CONF instead.
[Unit]
Description=vdl2-observatory receiver (vdl2-sniffer, live page on :$WEB_PORT)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=$RUN_USER
$GROUPS_LINE
EnvironmentFile=$CONF
WorkingDirectory=$DATA_DIR
ExecStart=$PREFIX/bin/vdl2-sniffer \$VDL2_ARGS --web=\${WEB_PORT} --observatory-port=\${OBS_PORT} --archive $ARCHIVE_DIR
Restart=always
RestartSec=10

[Install]
WantedBy=multi-user.target
EOF
root_write "$OBS_UNIT" 0644 <<EOF
$MARKER — don't edit; change $CONF instead.
[Unit]
Description=VDL2 Observatory dashboard on :$OBS_PORT
After=network.target

[Service]
Type=simple
User=$RUN_USER
EnvironmentFile=$CONF
ExecStart=$PY $PREFIX/observatory/server.py --db $DB_PATH --port \${OBS_PORT} --live-port \${WEB_PORT} --host 0.0.0.0
Restart=always
RestartSec=10

[Install]
WantedBy=multi-user.target
EOF
root_write "$ROLLUP_UNIT" 0644 <<EOF
$MARKER — don't edit; change $CONF instead.
[Unit]
Description=VDL2 Observatory: fold the archive into the database

[Service]
Type=oneshot
User=$RUN_USER
Nice=10
ExecStart=$PY $PREFIX/observatory/rollup.py --archive $ARCHIVE_DIR --db $DB_PATH
EOF
root_write "$ROLLUP_TIMER" 0644 <<EOF
$MARKER — don't edit; change $CONF instead.
[Unit]
Description=VDL2 Observatory rollup every minute

[Timer]
OnBootSec=1min
OnUnitActiveSec=1min

[Install]
WantedBy=timers.target
EOF
as_root systemctl daemon-reload
as_root systemctl enable vdl2-sniffer.service vdl2-observatory.service vdl2-rollup.timer
NO_SDR=0
if [ "${#RTLS[@]}" -gt 0 ]; then
  as_root systemctl restart vdl2-sniffer.service
  ok "vdl2-sniffer enabled and (re)started"
else
  as_root systemctl stop vdl2-sniffer.service 2>/dev/null || true
  warn "no RTL-SDR on USB — the receiver is enabled but not started. Plug it in, then: sudo systemctl start vdl2-sniffer"
  NO_SDR=1
fi
# A first rollup now, so the dashboard has something on first load.
if [ "$DRY_RUN" -eq 1 ]; then
  printf '  %s[dry-run]%s sudo -u %s %s\n' "$Y" "$Z" "$RUN_USER" "$PY $PREFIX/observatory/rollup.py --archive $ARCHIVE_DIR --db $DB_PATH"
elif sudo -u "$RUN_USER" "$PY" "$PREFIX/observatory/rollup.py" --archive "$ARCHIVE_DIR" --db "$DB_PATH" \
     > "$BUILD_DIR/rollup.log" 2>&1; then
  ok "first rollup done"
else
  warn "first rollup failed — see $BUILD_DIR/rollup.log (the timer will try again every minute)"
fi
as_root systemctl restart vdl2-observatory.service vdl2-rollup.timer
ok "Observatory and rollup timer enabled and (re)started"

# ---- health -----------------------------------------------------------------
info "Checking"
IP="$(hostname -I 2>/dev/null | awk '{print $1}')"; IP="${IP:-localhost}"
if [ "$DRY_RUN" -eq 1 ]; then
  ok "dry run — nothing was changed"
else
  if [ "$NO_SDR" -eq 1 ]; then
    warn "receiver not started (no RTL-SDR)"
  else
    up=0
    for _ in $(seq 1 20); do
      if curl -fs -o /dev/null "http://127.0.0.1:$WEB_PORT/healthz"; then up=1; break; fi
      sleep 1
    done
    if [ "$up" -eq 1 ]; then ok "live page answering on :$WEB_PORT"
    else
      warn "live page not answering on :$WEB_PORT yet — recent log:"
      journalctl -u vdl2-sniffer -n 15 --no-pager 2>/dev/null | sed 's/^/      /' || true
    fi
  fi
  up=0
  for _ in $(seq 1 10); do
    if curl -fs -o /dev/null "http://127.0.0.1:$OBS_PORT/healthz"; then up=1; break; fi
    sleep 1
  done
  [ "$up" -eq 1 ] && ok "Observatory answering on :$OBS_PORT" \
    || warn "Observatory not answering on :$OBS_PORT — journalctl -u vdl2-observatory"
fi

info "Done"
say "  Live page:    ${B}http://$IP:$WEB_PORT/${Z}"
say "  Observatory:  ${B}http://$IP:$OBS_PORT/${Z}   (fills in as the rollup runs, every minute)"
say "  Settings:     $CONF  then  sudo systemctl restart vdl2-sniffer"
say "  Logs:         journalctl -u vdl2-sniffer -f"
say "  Update:       ./install.sh --update"
if have ufw && [ "$DRY_RUN" -eq 0 ] && sudo ufw status 2>/dev/null | grep -q '^Status: active'; then
  warn "ufw is active — for LAN access:  sudo ufw allow $WEB_PORT/tcp && sudo ufw allow $OBS_PORT/tcp"
fi
